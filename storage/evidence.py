"""Small, permanent evidence committed to git (evidence/), complementing R2.

Git gets only what is small and enough to audit without the server:
* the lock, transition log and signed freeze records;
* every sealed shard record (hashes of plan/results/traces: the Merkle leaves);
* the R2 index (sha256 -> object key, bytes) so every R2 object is verifiable;
* human-readable reports and the gate evaluation;
* counterexamples and wrong payloads as their case lines (frames regenerate
  bit-for-bit from these) plus the production SVG, gzip -9, named by its SHA-256;
* the ML model card and weights (well under 1 MB).
A hard size cap (configs/campaign.yaml: evidence.max_total_mb) is enforced.
"""
from __future__ import annotations

import gzip
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

from generator.common import ROOT, load_yaml, worker_path


def _copy(src: Path, dst: Path) -> None:
    if src.exists():
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)


def svg_for(case: dict) -> str | None:
    with tempfile.TemporaryDirectory() as tmp:
        line = Path(tmp) / "c.json"
        line.write_text(json.dumps(case) + "\n")
        subprocess.run([str(worker_path()), "--repro", str(line), "--out", tmp], capture_output=True, check=False)
        f = Path(tmp) / "symbol.svg"
        return f.read_text() if f.exists() else None


def export(data_dir: Path, log=print) -> dict:
    cfg = load_yaml("campaign.yaml").get("evidence", {})
    max_svg, max_bytes = cfg.get("max_svg_files", 1500), cfg.get("max_total_mb", 40) * 1e6
    ev = ROOT / "evidence"
    ev.mkdir(exist_ok=True)
    for name in ("lock.json", "lock.json.sig", "transitions.jsonl"):
        _copy(data_dir / "state" / name, ev / "state" / name)
    for f in (data_dir / "manifests").glob("*.jsonl") if (data_dir / "manifests").exists() else []:
        _copy(f, ev / "manifests" / f.name)
    _copy(data_dir / "storage" / "uploaded.jsonl", ev / "r2_index.jsonl")
    for f in (data_dir / "reports").glob("*") if (data_dir / "reports").exists() else []:
        if f.is_file() and (f.suffix in (".md", ".sig") or f.name.endswith(".freeze.json") or (f.suffix == ".json" and f.stat().st_size < 2_000_000)):
            _copy(f, ev / "reports" / f.name)
    for f in (ROOT / "ml" / "models").glob("*") if (ROOT / "ml" / "models").exists() else []:
        if f.is_file() and f.stat().st_size < 2_000_000:
            _copy(f, ev / "ml" / f.name)
    # Counterexamples + wrong payloads: case lines and gzipped production SVGs.
    want = []
    for rep in ("counterexamples_structured.json",):
        p = data_dir / "reports" / rep
        if p.exists():
            cat = json.loads(p.read_text())
            want += [w["case_id"] for w in cat.get("wrong_payloads", [])]
            for cell in cat.get("cells", {}).values():
                want += [e["case_id"] for e in cell["examples"][:2]]
    mc = data_dir / "reports" / "minimal_counterexamples.json"
    if mc.exists():
        want += [t["base_case"] for t in json.loads(mc.read_text())[:300]]
    want = list(dict.fromkeys(want))[:max_svg]
    found = {}
    if want:
        from generator import plan as planmod
        wanted = set(want)
        for ps in sorted(p.name for p in (data_dir / "plans").iterdir()):
            for c in planmod.iter_plan(data_dir, ps):
                if c["case_id"] in wanted and c["case_id"] not in found:
                    found[c["case_id"]] = c
            if len(found) == len(wanted):
                break
    svgs = 0
    for cid, case in found.items():
        (ev / "counterexamples").mkdir(parents=True, exist_ok=True)
        (ev / "counterexamples" / f"{cid}.json").write_text(json.dumps(case, sort_keys=True, separators=(",", ":")))
        svg = svg_for(case)
        if svg:
            import hashlib
            h = hashlib.sha256(svg.encode()).hexdigest()
            out = ev / "svg" / f"{h}.svg.gz"
            if not out.exists():
                out.parent.mkdir(parents=True, exist_ok=True)
                with gzip.GzipFile(out, "wb", compresslevel=9, mtime=0) as fh:
                    fh.write(svg.encode())
                svgs += 1
    total = sum(f.stat().st_size for f in ev.rglob("*") if f.is_file())
    if total > max_bytes:
        raise SystemExit(f"evidence/ is {total / 1e6:.1f} MB > cap {max_bytes / 1e6:.0f} MB; lower evidence.max_svg_files")
    (ev / "README.md").write_text(
        "# Evidence (small, permanent, in git)\n\nGenerated by `./ckt export-evidence`. Large data lives in Cloudflare R2 "
        "(bucket `ckey-hardening-test`), content-addressed: every object is `cas/sha256/<aa>/<sha256>` and its hash is listed in "
        "`r2_index.jsonl` and in the shard records under `manifests/`.\n\n"
        "* `state/` lock (gate approval, config/spec/worker hashes) and transition log\n"
        "* `manifests/` one line per sealed 1,000-case shard: plan/results/traces SHA-256\n"
        "* `reports/` campaign reports, freeze records and signatures, gate evaluation\n"
        "* `counterexamples/<case_id>.json` exact case lines: `./ckt repro` regenerates the frames bit-for-bit\n"
        "* `svg/<sha256>.svg.gz` the production SVG of those cases (gzip -9); `svg_sha256` in results matches the uncompressed file\n"
        "* `ml/` model weights and model card\n")
    log(f"evidence/: {len(found)} counterexample cases, {svgs} new SVGs, {total / 1e6:.2f} MB total")
    return {"cases": len(found), "svgs": svgs, "bytes": total}
